#!/usr/bin/env python3
"""Generate the Ride function reference from node-scala's compiled standard library.

Usage:
    generate_ride_reference.py --node-scala <checkout> [--check] [--dump <file>]
    generate_ride_reference.py --dump <file> [--check]
    generate_ride_reference.py --print-commit

Writes one page per standard library version (V6-V9) under
03_ride-language/13_function-reference/, and 03_ride-language/09_complexity-changes.md.
Every page records NODE_SCALA_COMMIT, the node-scala commit it was generated from.

With --node-scala, the checkout must be at NODE_SCALA_COMMIT with no local
changes. The script copies ride_reference/RideFunctionDump.scala into its
lang/jvm module, runs it with sbt (JDK 17 and sbt on PATH), and deletes it
again. The dumper reads the same contexts the node evaluates scripts with, so a
cost set through a helper function (the BigInt operators, for example) comes
out exactly as the node charges it; nothing here parses Scala source.

--dump saves that JSON; without --node-scala, --dump reads a saved one instead,
which is quick for iterating on the page layout.

--check writes nothing and exits 1 if any page differs from what is committed.
CI (.github/workflows/ride_reference.yml) runs it on every pull request that
touches these pages or this generator, so a hand edit to a generated page fails.

To move to a newer node-scala: change NODE_SCALA_COMMIT, rerun, commit the pages.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

NODE_SCALA_COMMIT = "104ddc70e8007175e0d1306b6db527ad37bb1b1f"
NODE_SCALA_REPO = "https://github.com/Decentral-America/node-scala"
REFERENCE_VERSIONS = (6, 7, 8, 9)
# 09_complexity-changes.md compares against V5, the version the hand-written
# function pages (03_functions.rst) were written for.
COMPLEXITY_VERSIONS = (5, 6, 7, 8, 9)

DOCS = pathlib.Path(__file__).resolve().parent.parent
RIDE = DOCS / "03_ride-language"
REFERENCE_DIR = RIDE / "13_function-reference"
COMPLEXITY_PAGE = RIDE / "09_complexity-changes.md"
DUMPER = pathlib.Path(__file__).resolve().parent / "ride_reference" / "RideFunctionDump.scala"
DUMPER_TARGET = pathlib.Path("lang/jvm/src/main/scala/docgen/RideFunctionDump.scala")

GENERATED_BANNER = (
    "% Generated by docs/scripts/generate_ride_reference.py. Do not edit by hand:\n"
    "% CI regenerates this page from node-scala and fails if it differs.\n"
)

# Category ids are the hjson file names under node-scala's lang/doc/v<n>/funcs.
CATEGORY_TITLES = {
    "account-self-data-storage-functions": "Account self-data storage functions",
}

KIND_NOTES = {
    ("dapp",): "dApp scripts only.",
    ("account", "dapp"): "Not available in asset scripts.",
}

MARKDOWN_LINK = re.compile(r"\[(.+?)\]\(.+?\)")
TUPLE_UNION = re.compile(r"^\(A, B\)(\|\([A-Z](, [A-Z])*\))+$")


def run_dumper(checkout: pathlib.Path, out: pathlib.Path) -> None:
    head = subprocess.run(
        ["git", "-C", str(checkout), "rev-parse", "HEAD"], check=True, capture_output=True, text=True
    ).stdout.strip()
    if head != NODE_SCALA_COMMIT:
        sys.exit(f"{checkout} is at {head}, expected NODE_SCALA_COMMIT {NODE_SCALA_COMMIT}")
    dirty = subprocess.run(
        ["git", "-C", str(checkout), "status", "--porcelain", "--untracked-files=no"],
        check=True, capture_output=True, text=True,
    ).stdout.strip()
    if dirty:
        sys.exit(f"{checkout} has local changes; the reference must come from the pinned commit as-is:\n{dirty}")

    target = checkout / DUMPER_TARGET
    if target.exists():
        sys.exit(f"{target} already exists; remove it first")
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(DUMPER, target)
    try:
        # sbt's own output goes to stderr so that --check's verdict is the last thing on stdout.
        subprocess.run(
            ["sbt", "-batch", f"lang/runMain docgen.RideFunctionDump {out.resolve()}"],
            cwd=checkout, check=True, stdout=sys.stderr,
        )
    finally:
        target.unlink()
        if not any(target.parent.iterdir()):
            target.parent.rmdir()


def signature_key(f: dict) -> tuple:
    return f["name"], tuple(a["type"] for a in f["args"])


def lineages(dump: dict, versions: tuple[int, ...]) -> list[dict[int, dict]]:
    """Group each version's functions into one row per function as a script author sees it.

    Consecutive versions' entries belong together when they share a signature
    (name and argument types) or a function header. The signature catches V6's
    take/drop/takeRight/dropRight/addressFromPublicKey, which keep their
    signature but move to new headers; the header catches rsaVerify, whose
    digest-algorithm argument changes from the RsaDigestAlgs alias to the
    spelled-out union in V6 while the function itself stays the same.
    """
    rows: list[dict[int, dict]] = []
    previous: dict[int, dict] = {}  # id(entry) -> row, for the version before
    previous_entries: list[dict] = []
    for v in versions:
        by_signature = {signature_key(e): e for e in previous_entries}
        by_header = {e["header"]: e for e in previous_entries}
        current: dict[int, dict] = {}
        for f in dump[str(v)]["functions"]:
            before = by_signature.get(signature_key(f)) or by_header.get(f["header"])
            row = previous[id(before)] if before is not None else None
            if row is None or v in row:
                row = {}
                rows.append(row)
            row[v] = f
            current[id(f)] = row
        previous, previous_entries = current, dump[str(v)]["functions"]
    return rows


def plain(text: str) -> str:
    return " ".join(MARKDOWN_LINK.sub(r"\1", text).split())


def cell(text: str) -> str:
    return text.replace("|", "\\|")


def type_name(t: str) -> str:
    # tuple size() takes any tuple, spelled out by the compiler as all 21 tuple arities
    if TUPLE_UNION.match(t):
        return "(A, B)|(A, B, C)|…|(A, B, …, V)"
    return t


def signature(f: dict) -> str:
    args = ", ".join(f"{a['name'].lstrip('@')}: {type_name(a['type'])}" for a in f["args"])
    return f"{f['name']}({args}): {type_name(f['result'])}"


def category_title(category: str) -> str:
    return CATEGORY_TITLES.get(category, category.replace("-", " ").capitalize())


def provenance(v: int | None = None) -> str:
    short = NODE_SCALA_COMMIT[:10]
    version = f" at `STDLIB_VERSION {v}`" if v is not None else ""
    return (
        "```{note}\n"
        f"Generated from node-scala commit [`{short}`]({NODE_SCALA_REPO}/tree/{NODE_SCALA_COMMIT}) "
        "by `docs/scripts/generate_ride_reference.py`. The generator reads the compiled standard library "
        "the node evaluates scripts with, not the Scala source text, so every cost on this page is the one "
        f"the node charges{version}. "
        "To change this page, change the generator or move it to a newer node-scala commit and regenerate. "
        "CI fails on any hand edit.\n"
        "```\n"
    )


def render_version_page(dump: dict, v: int, rows: list[dict[int, dict]]) -> str:
    functions = dump[str(v)]["functions"]
    new = [r[v] for r in rows if v in r and v - 1 not in r]
    changed = [r for r in rows if v in r and v - 1 in r and r[v]["cost"] != r[v - 1]["cost"]]
    row_of = {id(r[v]): r for r in rows if v in r}

    out = [
        GENERATED_BANNER,
        f"# Ride V{v} Functions\n",
        provenance(v),
        f"`STDLIB_VERSION {v}` has **{len(functions)}** built-in functions and operators, counting each overload "
        f"separately: {len(new)} are new in V{v} and {len(changed)} cost a different amount than in V{v - 1}. "
        "Each table row is one overload, so a function with several signatures has one row per signature.\n",
        "**Complexity** is what one call adds to the script's complexity, as charged by the node's current "
        "estimator. The limits that complexity counts against are on "
        "{doc}`Limitations <../10_limitations>`. "
        "Unless the description says otherwise, a function is available in account scripts, asset scripts "
        "and dApp scripts alike.\n",
    ]

    categories = sorted({f["category"] for f in functions}, key=category_title)
    for category in categories:
        out.append(f"## {category_title(category)}\n")
        out.append("| Function | Complexity | Description |")
        out.append("|---|---|---|")
        for f in (f for f in functions if f["category"] == category):
            notes = []
            row = row_of[id(f)]
            if v - 1 not in row:
                notes.append(f"New in V{v}.")
            elif row[v - 1]["cost"] != f["cost"]:
                notes.append(f"Was {row[v - 1]['cost']} in V{v - 1}.")
            if tuple(f["kinds"]) in KIND_NOTES:
                notes.append(KIND_NOTES[tuple(f["kinds"])])
            elif tuple(f["kinds"]) != ("account", "asset", "dapp"):
                sys.exit(f"{f['name']}: no note for script kinds {f['kinds']}")
            description = plain(f["doc"])
            if description and description[-1] not in ".!?":
                description += "."
            if notes:
                description += " *" + " ".join(notes) + "*"
            out.append(f"| `{cell(signature(f))}` | {f['cost']} | {cell(description)} |")
        out.append("")
    return "\n".join(out)


def render_complexity_page(dump: dict, rows: list[dict[int, dict]]) -> str:
    vs = COMPLEXITY_VERSIONS
    changed = [r for r in rows if len({r[v]["cost"] for v in vs if v in r}) > 1]
    changed.sort(key=lambda r: (r[max(r)]["name"], signature(r[max(r)])))

    out = [
        GENERATED_BANNER,
        "# Complexity Changes by Version\n",
        "Every built-in function has a **complexity** cost, charged against a script's complexity limit. "
        "Several built-ins get cheaper (rarely, more expensive) at a later standard library version, "
        "with no change to their arguments or return type, so a script recompiled at a higher "
        "`STDLIB_VERSION` can pass where it previously failed the complexity limit, with no code change.\n",
        provenance(),
        f"The table lists every function whose cost differs anywhere between V{vs[0]} and V{vs[-1]}: "
        f"{len(changed)} rows, one per overload. "
        "A dash means the function does not exist at that version. "
        "Functions that are new in V6 to V9 appear here only if their cost changes after they are added; "
        "for everything a version adds, see {doc}`Standard Library Versions <08_stdlib-versions>`, and for "
        "the full list of functions and costs at one version, see the {doc}`function reference "
        "<13_function-reference/index>`.\n",
        "| Function | " + " | ".join(f"V{v}" for v in vs) + " |",
        "|---|" + "---|" * len(vs),
    ]
    for r in changed:
        latest = r[max(r)]
        costs = " | ".join(str(r[v]["cost"]) if v in r else "—" for v in vs)
        out.append(f"| `{cell(signature(latest))}` | {costs} |")
    out.append("")
    out.append(
        "Where a function's argument types are written differently at different versions, the row shows "
        "the newest spelling. For example, `rsaVerify` takes the digest algorithm as `RsaDigestAlgs` up to V5 "
        "and as the equivalent spelled-out union from V6."
    )
    out.append("")
    return "\n".join(out)


def render(dump: dict) -> dict[pathlib.Path, str]:
    reference_rows = lineages(dump, tuple(range(REFERENCE_VERSIONS[0] - 1, REFERENCE_VERSIONS[-1] + 1)))
    pages = {REFERENCE_DIR / f"v{v}.md": render_version_page(dump, v, reference_rows) for v in REFERENCE_VERSIONS}
    pages[COMPLEXITY_PAGE] = render_complexity_page(dump, lineages(dump, COMPLEXITY_VERSIONS))
    return pages


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--node-scala", type=pathlib.Path, help="node-scala checkout at NODE_SCALA_COMMIT")
    parser.add_argument("--dump", type=pathlib.Path, help="save the dumper's JSON here, or read it without --node-scala")
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 if any page is out of date")
    parser.add_argument("--print-commit", action="store_true", help="print NODE_SCALA_COMMIT and exit")
    args = parser.parse_args()

    if args.print_commit:
        print(NODE_SCALA_COMMIT)
        return 0
    if args.node_scala is None and args.dump is None:
        parser.error("give --node-scala, --dump, or both")

    if args.node_scala is not None:
        with tempfile.TemporaryDirectory() as tmp:
            out = args.dump or pathlib.Path(tmp) / "ride-functions.json"
            run_dumper(args.node_scala, out)
            dump = json.loads(out.read_text(encoding="utf-8"))
    else:
        dump = json.loads(args.dump.read_text(encoding="utf-8"))

    stale = []
    for path, text in render(dump).items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        stale.append(path.relative_to(DOCS.parent))
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")

    if args.check:
        for path in stale:
            print(f"FAIL {path} differs from what the generator produces; rerun it instead of editing by hand")
        print(f"{len(stale)} generated page(s) out of date")
        return 1 if stale else 0
    for path in stale:
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
